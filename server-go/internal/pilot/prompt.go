var visualKeywords = []string{
	"画", "图", "svg", "SVG", "绘制", "流程图", "架构图", "拓扑图", "走势图",
	"对比图", "柱状图", "折线图", "甘特图", "思维导图", "决策树", "可视化", "图表",
	"流程", "架构", "拓扑", "路线图", "时间线", "脉络", "调用链", "决策分支", "依赖关系",
}

func IsVisualRequest(question string) bool {
	for _, w := range visualKeywords {
		if strings.Contains(question, w) {
			return true
		}
	}
	return false
}

