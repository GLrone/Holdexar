//go:build windows

// comgen 从官方 WebView2.h（MIDL 生成头）机械抽取接口方法序，产出
// com_generated.go：槽位由脚本按头文件声明序计算（IUnknown 占 0-2），
// 人手不再数槽。用法：
//
//	go run ./tools/comgen -header WebView2.h -out com_generated.go
//
// 头文件来源与摘要写进产物头注释；COM 接口一经发布不可变，重跑可复现。
package main

import (
	"crypto/sha256"
	"flag"
	"fmt"
	"os"
	"regexp"
	"strings"
)

// emitRules 产物范围：接口 → 要产出的官方方法名。未列出的方法只参与槽位
// 计算，不产出包装。每一条都必须成功产出，否则生成器报错退出（防头文件
// 漂移时产物悄悄缺方法）。
var emitRules = map[string]map[string]bool{
	"ICoreWebView2": {
		"add_NavigationStarting": true,
		"add_NewWindowRequested": true,
	},
	"ICoreWebView2NavigationStartingEventArgs": {
		"get_Uri": true, "get_IsUserInitiated": true, "get_IsRedirected": true,
		"get_Cancel": true, "put_Cancel": true, "get_NavigationId": true,
	},
	"ICoreWebView2NewWindowRequestedEventArgs": {
		"get_Uri": true, "get_IsUserInitiated": true, "get_Handled": true, "put_Handled": true,
	},
	"ICoreWebView2ProcessFailedEventArgs": {
		"get_ProcessFailedKind": true,
	},
}

// shapeMap 官方方法（含 propget/propput 前缀）→ Go 方法名与调用形状。
// stringOut：LPWSTR* 出参读回；boolOut：BOOL* 出参读回；boolIn：[in] BOOL
// 按值传；uint32Out：枚举出参；uint64Out：UINT64 出参；register：事件注册
// （handler 入参 + EventRegistrationToken 出参）。
var shapeMap = map[string]struct {
	goName string
	shape  string
}{
	"propget:get_Uri":               {"Uri", "stringOut"},
	"propget:get_IsUserInitiated":   {"IsUserInitiated", "boolOut"},
	"propget:get_IsRedirected":      {"IsRedirected", "boolOut"},
	"propget:get_Cancel":            {"Canceled", "boolOut"},
	"propput:put_Cancel":            {"SetCancel", "boolIn"},
	"propget:get_Handled":           {"Handled", "boolOut"},
	"propput:put_Handled":           {"SetHandled", "boolIn"},
	"propget:get_NavigationId":      {"NavigationId", "uint64Out"},
	"propget:get_ProcessFailedKind": {"ProcessFailedKind", "uint32Out"},
	"m:add_NavigationStarting":      {"AddNavigationStarting", "register"},
	"m:add_NewWindowRequested":      {"AddNewWindowRequested", "register"},
}

var ifaceRe = regexp.MustCompile(
	`(?s)MIDL_INTERFACE\("([0-9a-fA-F-]{36})"\)\s*\n\s*(ICoreWebView2\w*)\s*:\s*public IUnknown\s*\n\s*\{(.*?)\n    \};`)
var methodRe = regexp.MustCompile(
	`(?s)virtual\s+(?:/\*\s*\[(propget|propput)\]\s*\*/\s*)?HRESULT\s+STDMETHODCALLTYPE\s+(\w+)\s*\(([^)]*)\)`)

type method struct {
	slot int    // 绝对 vtable 下标（IUnknown 0-2 起算）
	key  string // "propget:get_Uri" 形态
}

func main() {
	header := flag.String("header", "", "官方 WebView2.h 路径")
	out := flag.String("out", "", "输出 com_generated.go 路径")
	flag.Parse()
	raw, err := os.ReadFile(*header)
	if err != nil {
		fmt.Fprintln(os.Stderr, "读头文件失败：", err)
		os.Exit(1)
	}
	text := string(raw)
	digest := sha256.Sum256([]byte(text))

	ifaceBlocks := map[string]string{}
	for _, m := range ifaceRe.FindAllStringSubmatch(text, -1) {
		ifaceBlocks[m[2]] = m[3]
	}

	var b strings.Builder
	fmt.Fprintf(&b, "// Code generated by tools/comgen from the official WebView2 SDK header. DO NOT EDIT.\n")
	fmt.Fprintf(&b, "// 槽位由脚本按官方接口声明序机械计算（IUnknown 占 0-2），勿手改。\n")
	fmt.Fprintf(&b, "// 重生成：go run ./tools/comgen -header WebView2.h -out com_generated.go\n")
	fmt.Fprintf(&b, "// 头文件来源：github.com/jchv/OpenWebView2Loader Include/WebView2.h（sha256=%.16x）\n", digest)
	fmt.Fprintf(&b, "// COM 接口一经发布不可变，本文件槽位对新版运行时恒成立。\n\npackage main\n\nimport \"unsafe\"\n\n")

	fmt.Fprintf(&b, "// generatedSlots 官方接口 → 有序方法（kind:name）。机器抽取自官方头，\n")
	fmt.Fprintf(&b, "// 供核对测试与人工审阅；下方槽位常量逐条来自本表次序。\n")
	fmt.Fprintf(&b, "var generatedSlots = map[string][]string{\n")
	for iface := range emitRules {
		block, ok := ifaceBlocks[iface]
		if !ok {
			fmt.Fprintf(&b, "\t%q: {\"!! 官方头里未找到该接口\"},\n", iface)
			fmt.Fprintf(os.Stderr, "官方头里未找到接口 %s\n", iface)
			os.Exit(1)
		}
		var rows []string
		for i, mm := range methodRe.FindAllStringSubmatch(block, -1) {
			kind, name := mm[1], mm[2]
			if kind == "" {
				kind = "m"
			}
			rows = append(rows, fmt.Sprintf("%q, // 槽 %d", kind+":"+name, 3+i))
		}
		fmt.Fprintf(&b, "\t%q: {\n\t\t%s\n\t},\n", iface, strings.Join(rows, "\n\t\t"))
		fmt.Fprintf(&b, "\n")
	}
	fmt.Fprintf(&b, "}\n\n")

	// 槽位常量（由上表次序产出）。
	fmt.Fprintf(&b, "const (\n")
	for iface, methods := range emitRules {
		for i, mm := range methodRe.FindAllStringSubmatch(ifaceBlocks[iface], -1) {
			kind, name := mm[1], mm[2]
			if kind == "" {
				kind = "m"
			}
			if !methods[name] {
				continue
			}
			shape, ok := shapeMap[kind+":"+name]
			if !ok {
				fmt.Fprintf(os.Stderr, "%s.%s 在 shapeMap 缺少映射\n", iface, name)
				os.Exit(1)
			}
			fmt.Fprintf(&b, "\tslot%s%s = %d // %s.%s\n", iface, shape.goName, 3+i, iface, name)
		}
	}
	fmt.Fprintf(&b, ")\n\n")

	// 类型化包装：体只调 com.go 里的通用出/入参助手，槽位取上方常量。
	fmt.Fprintf(&b, "// CoreWebView2 主接口注册面（其余方法走 edge 库既有绑定，不在本层重复）。\n")
	fmt.Fprintf(&b, "type CoreWebView2 struct{ raw unsafe.Pointer }\n\n")
	fmt.Fprintf(&b, "func newCoreWebView2(raw unsafe.Pointer) *CoreWebView2 { return &CoreWebView2{raw: raw} }\n\n")
	fmt.Fprintf(&b, "// AddNavigationStarting 注册导航即将开始事件；handler 为 comEventHandler 指针。\n")
	fmt.Fprintf(&b, "func (w *CoreWebView2) AddNavigationStarting(handler unsafe.Pointer) error {\n")
	fmt.Fprintf(&b, "\treturn comRegister(w.raw, slotICoreWebView2AddNavigationStarting, handler)\n}\n\n")
	fmt.Fprintf(&b, "// AddNewWindowRequested 注册新窗口请求事件。\n")
	fmt.Fprintf(&b, "func (w *CoreWebView2) AddNewWindowRequested(handler unsafe.Pointer) error {\n")
	fmt.Fprintf(&b, "\treturn comRegister(w.raw, slotICoreWebView2AddNewWindowRequested, handler)\n}\n\n")

	fmt.Fprintf(&b, "// NavigationStartingArgs ICoreWebView2NavigationStartingEventArgs 包装。\n")
	fmt.Fprintf(&b, "type NavigationStartingArgs struct{ raw unsafe.Pointer }\n\n")
	fmt.Fprintf(&b, "func (v *NavigationStartingArgs) Uri() string { return comArgsString(v.raw, slotICoreWebView2NavigationStartingEventArgsUri) }\n")
	fmt.Fprintf(&b, "func (v *NavigationStartingArgs) IsUserInitiated() bool { return comArgsBool(v.raw, slotICoreWebView2NavigationStartingEventArgsIsUserInitiated) }\n")
	fmt.Fprintf(&b, "func (v *NavigationStartingArgs) IsRedirected() bool { return comArgsBool(v.raw, slotICoreWebView2NavigationStartingEventArgsIsRedirected) }\n")
	fmt.Fprintf(&b, "func (v *NavigationStartingArgs) Canceled() bool { return comArgsBool(v.raw, slotICoreWebView2NavigationStartingEventArgsCanceled) }\n")
	fmt.Fprintf(&b, "func (v *NavigationStartingArgs) SetCancel(on bool) { comArgsSetBool(v.raw, slotICoreWebView2NavigationStartingEventArgsSetCancel, on) }\n")
	fmt.Fprintf(&b, "func (v *NavigationStartingArgs) NavigationId() uint64 { return comArgsUint64(v.raw, slotICoreWebView2NavigationStartingEventArgsNavigationId) }\n\n")

	fmt.Fprintf(&b, "// NewWindowArgs ICoreWebView2NewWindowRequestedEventArgs 包装。\n")
	fmt.Fprintf(&b, "type NewWindowArgs struct{ raw unsafe.Pointer }\n\n")
	fmt.Fprintf(&b, "func (v *NewWindowArgs) Uri() string { return comArgsString(v.raw, slotICoreWebView2NewWindowRequestedEventArgsUri) }\n")
	fmt.Fprintf(&b, "func (v *NewWindowArgs) IsUserInitiated() bool { return comArgsBool(v.raw, slotICoreWebView2NewWindowRequestedEventArgsIsUserInitiated) }\n")
	fmt.Fprintf(&b, "func (v *NewWindowArgs) Handled() bool { return comArgsBool(v.raw, slotICoreWebView2NewWindowRequestedEventArgsHandled) }\n")
	fmt.Fprintf(&b, "func (v *NewWindowArgs) SetHandled(on bool) { comArgsSetBool(v.raw, slotICoreWebView2NewWindowRequestedEventArgsSetHandled, on) }\n\n")

	fmt.Fprintf(&b, "// ProcessFailedArgs ICoreWebView2ProcessFailedEventArgs 包装。\n")
	fmt.Fprintf(&b, "type ProcessFailedArgs struct{ raw unsafe.Pointer }\n\n")
	fmt.Fprintf(&b, "func (v *ProcessFailedArgs) ProcessFailedKind() uint32 { return comArgsUint32(v.raw, slotICoreWebView2ProcessFailedEventArgsProcessFailedKind) }\n")

	if err := os.WriteFile(*out, []byte(b.String()), 0o644); err != nil {
		fmt.Fprintln(os.Stderr, "写产物失败：", err)
		os.Exit(1)
	}
	fmt.Println("generated", *out)
}
